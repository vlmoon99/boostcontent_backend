-- ---------- 3. the style profile has a fixed shape ----------
create function private.text_of(j jsonb) returns text          -- a string, or a list read as one string
language sql immutable as $$
  select case jsonb_typeof(j)
           when 'string' then j #>> '{}'
           when 'number' then j #>> '{}'
           when 'array' then (select coalesce(string_agg(x, ', '), '') from jsonb_array_elements_text(j) x)
           else '' end
$$;

create function private.str_list(j jsonb, max_items int default 10) returns jsonb   -- always an array of strings
language sql immutable as $$
  select coalesce(jsonb_agg(btrim(x) order by o), '[]'::jsonb)
  from (select x, o from jsonb_array_elements_text(case jsonb_typeof(j) when 'array' then j
                                                     when 'string' then jsonb_build_array(j) else '[]'::jsonb end)
                        with ordinality t(x, o)
        where btrim(x) <> '' order by o limit max_items) s
$$;

-- Whatever the model (or the app) sent, these five keys exist with these types:
--   customers, tone, business_name: string ('' when unknown)
--   best_days:    array of lower-case English day names, Monday first, [] when unknown
--   brand_colors: array of at most 5 '#rrggbb' in lower case, [] when unknown
-- Every other key is kept as it came.
create function private.profile_shape(d jsonb) returns jsonb
language sql immutable as $$
  with o as (select case when jsonb_typeof(d) = 'object' then d else '{}'::jsonb end as d),
  days as (
    select lower(x) as x
    from o, jsonb_array_elements_text(case jsonb_typeof(o.d->'best_days')
           when 'array' then o.d->'best_days'
           when 'string' then to_jsonb(regexp_split_to_array(o.d->>'best_days', '\s*[,;/]\s*|\s+and\s+'))
           else '[]'::jsonb end) x)
  select o.d || jsonb_build_object(
    'customers', private.text_of(o.d->'customers'),
    'tone', private.text_of(o.d->'tone'),
    'business_name', left(btrim(private.text_of(o.d->'business_name')), 120),
    'best_days', (select coalesce(jsonb_agg(w.day order by w.n), '[]'::jsonb)
                  from unnest(array['monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday', 'sunday'])
                       with ordinality w(day, n)
                  where exists (select 1 from days where x ~ ('\m' || left(w.day, 3) || '(' || substr(w.day, 4) || ')?s?\M')
                                   or (x ~ 'weekend' and w.n >= 6) or (x ~ 'weekday' and w.n <= 5)
                                   or x ~ '\m(every ?day|daily|all days)\M')),
    'brand_colors', (select coalesce(jsonb_agg(lower(c) order by n), '[]'::jsonb)
                     from (select c, n from jsonb_array_elements_text(case when jsonb_typeof(o.d->'brand_colors') = 'array'
                                                                           then o.d->'brand_colors' else '[]'::jsonb end)
                                         with ordinality t(c, n)
                           where c ~ '^#[0-9a-fA-F]{6}$' order by n limit 5) s))
  from o
$$;

update private.profiles set data = private.profile_shape(data) where data is not null;

create or replace function api.update_profile(business_id uuid, data jsonb) returns api.profiles
language plpgsql security definer set search_path = private as $$
declare
  b private.businesses := private.own_business(update_profile.business_id);
  before jsonb;
  r api.profiles;
begin
  if jsonb_typeof(data) <> 'object' then
    raise exception 'profile must be a JSON object' using errcode = 'P0001', detail = 'bad_profile';
  end if;
  data := private.profile_shape(data);
  select p.data into before from private.profiles p where p.business_id = b.id;
  update private.profiles set data = update_profile.data, edited = true, status = 'ready', updated_at = now()
  where private.profiles.business_id = b.id;
  insert into private.signals (account_id, business_id, kind, data)
  values (b.account_id, b.id, 'profile_edited', jsonb_build_object('before', before, 'after', data));
  select * into r from api.profiles where api.profiles.business_id = b.id;
  return r;
end $$;

-- ---------- 4. download links ----------
-- sigv4_query gets `extra`: more query parameters to sign, already encoded, each starting with '&'. They must
-- sort after 'X-Amz-…' (S3's response-… overrides do: lower case sorts after upper case).
drop function private.sigv4_query(text, text, text, text, text, text, int, timestamptz);
create function private.sigv4_query(method text, host text, path text, region text, access_key text,
                                    secret text, expires_s int, at timestamptz default now(),
                                    extra text default '') returns text
language plpgsql immutable strict as $$
declare
  amz_date text := to_char(at at time zone 'UTC', 'YYYYMMDD"T"HH24MISS"Z"');
  day text := to_char(at at time zone 'UTC', 'YYYYMMDD');
  scope text := day || '/' || region || '/s3/aws4_request';
  q text;
  canonical text;
  to_sign text;
  k bytea;
begin
  q := 'X-Amz-Algorithm=AWS4-HMAC-SHA256'
    || '&X-Amz-Credential=' || private.uri_encode(access_key || '/' || scope)
    || '&X-Amz-Date=' || amz_date
    || '&X-Amz-Expires=' || expires_s
    || '&X-Amz-SignedHeaders=host'
    || extra;
  canonical := method || E'\n' || path || E'\n' || q || E'\n' || 'host:' || host || E'\n' || E'\n'
            || 'host' || E'\n' || 'UNSIGNED-PAYLOAD';
  to_sign := 'AWS4-HMAC-SHA256' || E'\n' || amz_date || E'\n' || scope || E'\n'
          || encode(digest(convert_to(canonical, 'UTF8'), 'sha256'), 'hex');
  k := private.hmac256(day, convert_to('AWS4' || secret, 'UTF8'));
  k := private.hmac256(region, k);
  k := private.hmac256('s3', k);
  k := private.hmac256('aws4_request', k);
  return q || '&X-Amz-Signature=' || encode(private.hmac256(to_sign, k), 'hex');
end $$;

-- A link that makes the browser save the object under `filename` (public audience, GET).
create function private.media_download_url(object_key text, filename text, expires_s int default 3600) returns text
language plpgsql stable security definer set search_path = private, public as $$
declare
  endpoint text := rtrim(private.setting('s3_public_endpoint'), '/');
  host text;
  path text;
begin
  if endpoint is null then
    raise exception 'storage not configured (s3_public_endpoint)';
  end if;
  host := split_part(regexp_replace(endpoint, '^https?://', ''), '/', 1);
  path := '/' || private.setting('s3_bucket', 'bc-media') || '/' || private.uri_encode(object_key, true);
  return endpoint || path || '?' || private.sigv4_query('GET', host, path, private.setting('s3_region', 'garage'),
         private.setting('s3_access_key'), private.setting('s3_secret_key'), expires_s, now(),
         '&response-content-disposition=' || private.uri_encode(format('attachment; filename="%s"', filename)));
end $$;

