-- The zone to store: an IANA name (checked), or minutes east of UTC turned into a POSIX zone
-- (`<+05:30>-05:30`: POSIX counts west as positive, so the sign is turned around).
create function private.tz(timezone text, utc_offset int) returns text
language plpgsql stable as $$
declare a int := abs(utc_offset);
begin
  if nullif(btrim(timezone), '') is not null then
    perform now() at time zone timezone;
    return timezone;
  end if;
  if utc_offset is null then
    return null;
  end if;
  if utc_offset not between -720 and 840 then
    raise exception 'utc_offset is minutes east of UTC, -720..840' using errcode = 'P0001', detail = 'bad_timezone';
  end if;
  return format('<%s%s:%s>%s%s:%s', case when utc_offset < 0 then '-' else '+' end, lpad((a / 60)::text, 2, '0'),
                lpad((a % 60)::text, 2, '0'), case when utc_offset < 0 then '+' else '-' end,
                lpad((a / 60)::text, 2, '0'), lpad((a % 60)::text, 2, '0'));
exception when invalid_parameter_value then
  raise exception 'unknown time zone' using errcode = 'P0001', detail = 'bad_timezone';
end $$;

drop function api.create_business(text, text, text, text);
create function api.create_business(name text default null, description text default '', language text default 'uk',
                                    timezone text default null, utc_offset int default null) returns api.businesses
language plpgsql security definer set search_path = private as $$
declare
  acc uuid := private.current_account();
  b private.businesses;
  r api.businesses;
begin
  if (select count(*) from private.businesses where account_id = acc and deleted_at is null) >= 50 then
    raise exception 'too many businesses' using errcode = 'PT409', detail = 'limit_businesses';
  end if;
  insert into private.businesses (account_id, name, description, language, timezone)
  values (acc, nullif(btrim(create_business.name), ''), coalesce(create_business.description, ''),
          create_business.language,
          coalesce(private.tz(create_business.timezone, create_business.utc_offset), 'Europe/Kyiv'))
  returning * into b;
  insert into private.profiles (business_id, account_id) values (b.id, acc);
  select * into r from api.businesses where id = b.id;
  return r;
end $$;

