-- One learn job waits per business at most; it reads every signal since the last one when it starts.
create function private.queue_learn(b uuid) returns void
language sql security definer set search_path = private as $$
  insert into private.jobs (kind, account_id, business_id, priority, max_attempts)
  select 'learn', x.account_id, x.id, -5, 2 from private.businesses x
  where x.id = b and x.deleted_at is null
    and not exists (select 1 from private.jobs j where j.business_id = b and j.kind = 'learn' and j.status = 'queued')
$$;

