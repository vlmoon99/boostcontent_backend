-- The owner keeps this option. The rest of its batch is passed: what has not started is stopped, and the
-- account gets those posts and pictures back, so a round of options costs one post.
create function api.choose_post(post_id uuid) returns api.posts
language plpgsql security definer set search_path = private as $$
declare
  p private.posts;
  o private.posts;
  live int;
  r api.posts;
begin
  select * into p from private.posts
  where id = post_id and account_id = private.current_account() and deleted_at is null for update;
  if not found then
    raise exception 'post not found' using errcode = 'PT404', detail = 'not_found';
  end if;
  if p.chosen_at is null then
    if p.passed_at is not null
       or exists (select 1 from private.posts x where x.batch_id = p.batch_id and x.chosen_at is not null) then
      raise exception 'another option of this round was already chosen' using errcode = 'PT409', detail = 'already_chosen';
    end if;
    if p.status not in ('ready', 'partial') then
      raise exception 'this option is not finished yet' using errcode = 'PT409', detail = 'not_ready';
    end if;
    update private.posts set chosen_at = now() where id = p.id;
    insert into private.signals (account_id, post_id, business_id, kind, data)
    values (p.account_id, p.id, p.business_id, 'chosen', jsonb_build_object('batch_id', p.batch_id, 'idea_en', p.idea_en));
    for o in select * from private.posts x where x.batch_id = p.batch_id and x.id <> p.id and x.passed_at is null
             order by x.created_at, x.id for update loop
      update private.posts set passed_at = now() where id = o.id;
      insert into private.signals (account_id, post_id, business_id, kind, data)
      values (o.account_id, o.id, o.business_id, 'passed', jsonb_build_object('batch_id', o.batch_id, 'idea_en', o.idea_en));
      if o.status <> 'failed' then            -- a failed post was given back when it failed
        select count(*) into live from private.post_images i where i.post_id = o.id and i.status <> 'failed';
        update private.jobs set status = 'failed', error = 'option not chosen', finished_at = now()
        where jobs.post_id = o.id and kind = 'image' and status = 'queued';
        update private.post_images set status = 'failed', error = 'option not chosen'
        where post_images.post_id = o.id and status = 'queued';
        perform private.refund(o.account_id, o.quota_month, live, 1);
        perform private.settle_post(o.id);
      end if;
    end loop;
    perform private.queue_learn(p.business_id);
  end if;
  select * into r from api.posts where id = p.id;
  return r;
end $$;

create or replace function api.edit_post(post_id uuid, caption text, hashtags text[] default null) returns api.posts
language plpgsql security definer set search_path = private as $$
declare
  p private.posts;
  r api.posts;
begin
  select * into p from private.posts where id = post_id and account_id = private.current_account() and deleted_at is null;
  if not found then
    raise exception 'post not found' using errcode = 'PT404', detail = 'not_found';
  end if;
  insert into private.signals (account_id, post_id, business_id, kind, data)
  values (p.account_id, p.id, p.business_id, 'edited', jsonb_build_object(
    'before', jsonb_build_object('caption', p.caption, 'hashtags', p.hashtags),
    'after', jsonb_build_object('caption', caption, 'hashtags', coalesce(hashtags, p.hashtags)),
    'idea_en', p.idea_en));
  update private.posts set caption = edit_post.caption, hashtags = coalesce(edit_post.hashtags, posts.hashtags)
  where id = p.id;
  perform private.queue_learn(p.business_id);
  select * into r from api.posts where id = p.id;
  return r;
end $$;

